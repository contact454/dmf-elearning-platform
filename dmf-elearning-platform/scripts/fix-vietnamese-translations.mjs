async function main() {
  const client = new Client({
    connectionString: process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/dmf_learning_db'
  });

  try {
    await client.connect();
    console.log('Connected to database');

    // Get all vocabulary items
    const result = await client.query('SELECT id, word, meaning_vi FROM "Vocabulary"');
    console.log(`Found ${result.rows.length} vocabulary items`);

    let updatedCount = 0;
    let skippedCount = 0;
    const missingTranslations = [];

    for (const row of result.rows) {
      const word = row.word;
      const currentMeaningVi = row.meaning_vi;

      // Check if translation exists in our map
      if (translations[word]) {
        const newMeaningVi = translations[word];

        // Only update if different
        if (currentMeaningVi !== newMeaningVi) {
          await client.query(
            'UPDATE "Vocabulary" SET meaning_vi = $1, "updatedAt" = NOW() WHERE id = $2',
            [newMeaningVi, row.id]
          );
          console.log(`Updated: "${word}" -> "${newMeaningVi}"`);
          updatedCount++;
        } else {
          skippedCount++;
        }
      } else {
        // Log missing translations
        if (!missingTranslations.includes(word)) {
          missingTranslations.push(word);
        }
        skippedCount++;
      }
    }

    console.log(`\nDone! Updated: ${updatedCount}, Skipped: ${skippedCount}`);
    if (missingTranslations.length > 0) {
      console.log(`\nMissing translations (${missingTranslations.length}):`);
      missingTranslations.slice(0, 20).forEach(w => console.log(`  - "${w}"`));
      if (missingTranslations.length > 20) {
        console.log(`  ... and ${missingTranslations.length - 20} more`);
      }
    }

  } catch (error) {
    console.error('Error:', error);
  } finally {
    await client.end();
  }
}

